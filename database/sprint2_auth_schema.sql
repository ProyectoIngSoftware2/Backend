-- Sprint 2 - Option B auth schema (Phase 2).
--
-- Creates the unified authentication table `public.usuarios` and links
-- it 1:1 to the existing `administradores` and `clientes` tables.
--
-- SAFETY / IDEMPOTENCY:
--   * Every statement is guarded (CREATE TABLE IF NOT EXISTS /
--     ADD COLUMN IF NOT EXISTS) so re-running changes nothing.
--   * No data is modified here; see sprint2_auth_seed.sql for the
--     idempotent test-admin seed.
--   * STATUS: written in Phase 2 but NOT executed yet - running it
--     requires explicit team approval (repository safety rule: no
--     schema changes executed without approval).
--
-- Design notes (Option B):
--   * Login credentials live ONLY in `usuarios` (correo + bcrypt
--     password_hash + rol). The legacy `administradores.password_hash`
--     column is kept for compatibility but is no longer read by the
--     auth service.
--   * `usuarios.id_usuario` has no outgoing FK: the reference direction
--     is administradores.id_usuario -> usuarios.id_usuario and
--     clientes.id_usuario -> usuarios.id_usuario (avoids a circular
--     dependency and lets a usuario row exist before its profile row).
-- =====================================================================

-- 1) Unified authentication table.
CREATE TABLE IF NOT EXISTS public.usuarios (
    id_usuario     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo         varchar(255) NOT NULL,
    password_hash  varchar(255) NOT NULL,
    rol            varchar(20)  NOT NULL,
    activo         boolean      NOT NULL DEFAULT true,
    fecha_creacion timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT usuarios_correo_key UNIQUE (correo),
    CONSTRAINT usuarios_rol_check CHECK (rol IN ('administrador', 'cliente'))
);

-- 2) 1:1 link from administradores to its login account.
--    UNIQUE keeps it 1:1; IF NOT EXISTS keeps the script idempotent.
ALTER TABLE public.administradores
    ADD COLUMN IF NOT EXISTS id_usuario bigint
    UNIQUE REFERENCES public.usuarios (id_usuario);

-- 3) 1:1 link from clientes to its login account (nullable for now:
--    existing customers have no login account yet).
ALTER TABLE public.clientes
    ADD COLUMN IF NOT EXISTS id_usuario bigint
    UNIQUE REFERENCES public.usuarios (id_usuario);

