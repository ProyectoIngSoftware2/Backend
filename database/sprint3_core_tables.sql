-- Sprint 3 - Core business API tables.
--
-- Creates tables required by the two new Sprint 3 API resources:
--   * horarios y bloqueos (catalogo service)
--   * roles (identidad, for usuarios y roles API)
--
-- SAFETY / IDEMPOTENCY:
--   * Every statement is guarded (CREATE TABLE IF NOT EXISTS /
--     ADD COLUMN IF NOT EXISTS) so re-running changes nothing.
--   * No existing tables or columns are modified.
--   * Uses BIGINT identifiers to match the live database convention.
--
-- Tables created:
--   public.roles            - identity roles (administrador, cliente)
--   public.horarios         - operating hours / reservable slots
--   public.bloqueos_horario - blocked periods (table-specific or general)
-- =====================================================================

-- 1) Roles table (identity).
--    The usuarios table already has a CHECK constraint on rol, but no
--    roles table exists in the live database. This table is the source
--    of truth for role management via the API.
CREATE TABLE IF NOT EXISTS public.roles (
    id_rol       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       varchar(40) NOT NULL UNIQUE,
    descripcion  varchar(180),
    activo       boolean     NOT NULL DEFAULT true
);

-- Seed the two roles that already exist in the usuarios CHECK constraint.
INSERT INTO public.roles (nombre, descripcion, activo)
VALUES
    ('administrador', 'Acceso total al sistema: usuarios, mesas, horarios, menú, reportes', true),
    ('cliente', 'Acceso de cliente: consultar disponibilidad, crear y gestionar propias reservas', true)
ON CONFLICT (nombre) DO NOTHING;

-- 2) Horarios table (catalogo).
--    Defines operating days and reservable time slots.
CREATE TABLE IF NOT EXISTS public.horarios (
    id_horario        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana        smallint NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    hora_apertura     time     NOT NULL,
    hora_cierre       time     NOT NULL,
    intervalo_minutos smallint NOT NULL CHECK (intervalo_minutos > 0),
    activo            boolean  NOT NULL DEFAULT true,
    CONSTRAINT horarios_cierre_despues_apertura_check
        CHECK (hora_cierre > hora_apertura)
);

-- 3) Bloqueos_horario table (catalogo).
--    Blocks a specific table or a general time period.
CREATE TABLE IF NOT EXISTS public.bloqueos_horario (
    id_bloqueo   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mesa      bigint REFERENCES public.mesas(id_mesa),
    inicio       timestamptz NOT NULL,
    fin          timestamptz NOT NULL CHECK (fin > inicio),
    motivo       varchar(180) NOT NULL,
    creado_por   bigint REFERENCES public.usuarios(id_usuario),
    fecha_creacion timestamptz NOT NULL DEFAULT now()
);

