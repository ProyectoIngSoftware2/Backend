-- =====================================================================
-- Sprint 5 - Transactional Outbox pattern for event publishing.
--
-- Creates the outbox_events table used by the reservas microservice to
-- record events that must be published to Redis Streams asynchronously.
-- The outbox pattern ensures that events are never lost even if Redis
-- is temporarily unavailable: the event is written in the same database
-- transaction as the business operation, and a separate publisher
-- process delivers it to Redis.
--
-- SAFETY / IDEMPOTENCY:
--   * CREATE TABLE IF NOT EXISTS so re-running changes nothing.
--   * No existing tables or columns are modified.
--   * Uses BIGINT identifiers to match the live database convention.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.outbox_events (
    id_evento       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_evento     varchar(80) NOT NULL,
    payload         jsonb NOT NULL,
    procesado       boolean NOT NULL DEFAULT false,
    fecha_creacion  timestamptz NOT NULL DEFAULT now(),
    fecha_procesado timestamptz,
    intentos        smallint NOT NULL DEFAULT 0,
    error           text
);

-- Index for efficient polling of unprocessed events.
CREATE INDEX IF NOT EXISTS idx_outbox_events_pendientes
    ON public.outbox_events (procesado, fecha_creacion)
    WHERE procesado = false;

